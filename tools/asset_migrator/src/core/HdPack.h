#pragma once
// HD pack import: one hires folder of a Classic REbirth texture pack for the
// Japanese PC release (Seamless HD Project, RE-ENHANCE) -> this port's HD/
// folder. A pack's hires folder is for the original game; the Seamless HD
// Project's bio1dc/hires is for the Director's Cut camera angles. The caller
// says which (HdPackGame).
//
// Those packs name each file after Classic REbirth's own hash of the picture it
// replaces, which mostly cannot be recomputed from the game's files (docs/
// HD_TEXTURES.md). The importer finds each file's texture other ways:
//
//  1. A table pairing pack names with the game files they replace
//     (HdPackTable.inc, generated by tools/gen_hd_pack_table.py by comparing
//     the pictures). Each is written under the file's own path, which is how
//     the game finds it (src/game/RoomBackgroundWebp.h, src/system/
//     HdTextures.h). Original game -> HD/<USA|JPN>/: room backgrounds
//     (Stage1/RC1060), masks (Objspr/OSP01060), character and enemy skins
//     (Enemy/EM1010; the pack's two per-palette pictures joined into one) and
//     Data/ textures (Data/STATUS). Director's Cut -> HD/DC/: backgrounds and
//     the masks kept in the arrange room files (Stage8/ROOM8000_MASK3).
//  2. Original game only, everything else: the game's own texture dump,
//     <target>/HD/dump (written with [Textures] DumpTextures=1). A dumped
//     texture is paired with the pack file of the name Classic REbirth would
//     give its pixels, when there is one, and otherwise with the pack picture
//     that shows the same thing - whole, or as the top-left part of a 256x256
//     page picture, which is then cut out with ffmpeg - and written under its
//     hash to HD/<pack folder>/. What the game has not dumped cannot be matched,
//     and a hash depends on the tree's background format: re-run the import
//     after changing it.

#include "core/Types.h"

#include <string>

namespace re1 {

// Which game a pack's hires folder is for.
enum class HdPackGame {
    // The original PC game (the packs' own hires/): names come from the base
    // tree and go to HD/<USA|JPN>/ (or by hash to HD/<type>/).
    Original,
    // The Director's Cut camera angles (the Seamless HD Project's
    // bio1dc/hires): names come from the DC overlay and go to HD/DC/.
    DirectorsCut,
};

struct HdPackOptions {
    // A pack's hires folder: it holds one or more of bgd, mask, misc, skin and
    // skin2.
    std::string packDir;
    HdPackGame game = HdPackGame::Original;
    // Game folder holding USA/ or JPN/; HD/ is written beside them.
    std::string targetRoot;
    // The tree whose files the names are computed from.
    AssetVersion tree = AssetVersion::USA;
    // Used to cut a texture out of a page picture; only those need it.
    std::string ffmpegPath = "ffmpeg";
};

// Imports every pack file that can be matched with confidence. What is left
// out is counted in the log, not an error.
bool importHdPack(const HdPackOptions& opts, const Progress& progress,
                  std::string* error);

// HD movies: the Seamless HD Project's movie folder (H.264 + AAC .mp4, one per
// PC FMV) -> <target>/HD/<USA|JPN>/Movie/<FMV name>.mp4. The game plays that
// file in place of the tree's movie of the same name while HD textures are on
// (src/video/VideoPlayback.cpp, CheckVideoFileExists); the tree is left alone.
// The pack is named after the Japanese release's movies (OJ, PJ, Ed4, Ed5,
// Stfc_B ...); for the USA tree those become OU, PU, EU4, EU5 and STFC_R ...
//
// Two movies come in alternative cuts, in "Capcom clips/<cut>" and
// "DM7 clips/<cut>"; the main folder holds the "Original" cut of both.
enum class HdCapcomIntro { PackDefault, Cubes, Original };
enum class HdDm7Clip { PackDefault, JillScene, Original };

struct HdMovieOptions {
    // The pack's movie folder.
    std::string movieDir;
    // Game folder holding USA/ or JPN/; HD/ is written beside them.
    std::string targetRoot;
    // The tree whose FMV names the files take (HD/USA or HD/JPN).
    AssetVersion tree = AssetVersion::USA;
    HdCapcomIntro capcom = HdCapcomIntro::PackDefault;
    HdDm7Clip dm7 = HdDm7Clip::PackDefault;
};

bool importHdMovies(const HdMovieOptions& opts, const Progress& progress,
                    std::string* error);

}  // namespace re1
