#!/usr/bin/env python3
"""Generate src/game/saturn/SaturnTickAnim.cpp from the Saturn's GAME2.PRG.

The Saturn Tick (the Hunter body GAME2 carries for stage byte 2) is animated by
its own keyframe tables rather than the EMD's PS1 animation section for four
of its poses: the walk (anim 0x80), the stab wind-up (0x81), the retract
(0x82) and the decapitation (0x83). The tables sit in GAME2's data segment:

    0x0609B878  4 x 12-byte entries (to the SCA record at 0x0609B8A8),
                index = animation id & 0xF
                  +0  u16  frame count
                  +2  u16  (0)
                  +4  u32  root key array (translation keys)
                  +8  u32  pointer to u32[16] - one rotation key array per joint
    key array   8-byte records {u16 time, s16 x, s16 y, s16 z}, one per frame,
                terminated by a record whose time is 0xFFFE

Everything is big-endian SH-2 data loaded at 0x0602B000 (the .PRG is the loaded
image verbatim). Run from the repo root:

    python tools/gen_tick_tables.py            # rewrites SaturnTickAnim.cpp
    python tools/gen_tick_tables.py --check    # exits 1 when the file is stale

The animator that consumes this is saturn/SaturnTick.cpp (GAME2 0x06070604).
"""
import argparse
import os
import struct
import sys

BASE = 0x0602B000
PRG = os.path.join("assets", "SATURN_ISO_CONTENT", "GAME2.PRG")
OUT = os.path.join("src", "game", "saturn", "SaturnTickAnim.cpp")
TABLE = 0x0609B878
ANIMS = 4
JOINTS = 16
END_TIME = 0xFFFE


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    d = open(PRG, "rb").read()

    def u32(addr):
        o = addr - BASE
        return struct.unpack(">I", d[o:o + 4])[0]

    def u16(addr):
        o = addr - BASE
        return struct.unpack(">H", d[o:o + 2])[0]

    def s16(addr):
        o = addr - BASE
        return struct.unpack(">h", d[o:o + 2])[0]

    keys = []          # flat list of (t, x, y, z)
    index_of = {}      # source address -> first record index in `keys`

    def take(addr):
        """Copy one key array (through its 0xFFFE sentinel) once; return index."""
        if addr in index_of:
            return index_of[addr]
        first = len(keys)
        index_of[addr] = first
        p = addr
        while True:
            t = u16(p)
            keys.append((t, s16(p + 2), s16(p + 4), s16(p + 6)))
            p += 8
            if t == END_TIME:
                break
            if len(keys) - first > 4096:
                sys.exit("runaway key array at 0x%08X" % addr)
        return first

    anims = []
    for i in range(ANIMS):
        e = TABLE + 12 * i
        frames = u16(e)
        root = take(u32(e + 4))
        jarr = u32(e + 8)
        joints = [take(u32(jarr + 4 * j)) for j in range(JOINTS)]
        anims.append((frames, root, joints, e))

    out = []
    w = out.append
    w("// SaturnTickAnim.cpp - GENERATED by tools/gen_tick_tables.py. Do not edit.")
    w("//")
    w("// The Sega Saturn Tick's own keyframe animations (GAME2.PRG data segment).")
    w("// %d key records in %d arrays, %d animations. See saturn/SaturnTick.h." % (
        len(keys), len(index_of), ANIMS))
    w("#include \"SaturnTick.h\"")
    w("")
    w("// One flat pool; every animation indexes into it. Each array ends with a")
    w("// record whose time is 0xFFFE.")
    w("const SaturnTickKey g_saturnTickKeys[%d] = {" % len(keys))
    for t, x, y, z in keys:
        w("    { 0x%04X, %d, %d, %d }," % (t, x, y, z))
    w("};")
    w("")
    w("// GAME2 0x0609B878. Index = animation id & 0xF (0x80 walk, 0x81 stab, 0x82 retract,")
    w("// 0x83 decapitation).")
    w("const SaturnTickAnim g_saturnTickAnims[SATURN_TICK_ANIMS] = {")
    for frames, root, joints, e in anims:
        w("    { %d, %d, {  // 0x%08X" % (frames, root, e))
        for j in range(0, JOINTS, 8):
            w("        " + ", ".join("%d" % v for v in joints[j:j + 8]) + ",")
        w("    } },")
    w("};")
    w("")
    text = "\n".join(out)

    if a.check:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("stale:", OUT)
            return 1
        print("ok:", OUT)
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d key records)" % (OUT, len(keys)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
