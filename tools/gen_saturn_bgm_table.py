#!/usr/bin/env python3
"""Generate tools/asset_migrator/src/core/SaturnBgmTable.h from the port's
g_BgmNameTable (src/game/SoundTables.cpp, 0x004d07b8).

The PC picks a room's music as a BGM *group*; g_BgmNameTable[group][slot] is the
wav loaded into channel `slot`. The Saturn's music packs are named by the same
group: /SND/BGM<group in hex>.CDP, and song k of the pack is channel k (the
Battle Game's group 0x34, BGM34B.CDP song 2, is the PC's Bgm_24 - the table row
for group 52 is {Se_55, Bgm_20, Bgm_24}). So the (group, slot) -> name table is
all the migrator needs to render every campaign BGM under the name the game
asks for.

Only "Bgm_*" names are taken: the "Se_*", "chain1" and "V110_00" entries share
the table but are sound effects / voices, which are not the music.

    python tools/gen_saturn_bgm_table.py          # rewrite the header
    python tools/gen_saturn_bgm_table.py --check  # exit 1 when it is stale
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "game" / "SoundTables.cpp"
OUT = ROOT / "tools" / "asset_migrator" / "src" / "core" / "SaturnBgmTable.h"


def parse():
    text = SRC.read_text(encoding="utf-8", errors="replace")
    m = re.search(r"g_BgmNameTable\[57\]\[4\]\s*=\s*\{(.*?)\n\};", text, re.S)
    if not m:
        sys.exit("g_BgmNameTable not found in %s" % SRC)
    rows = []
    for line in m.group(1).splitlines():
        r = re.match(r"\s*\{(.*?)\},\s*//\s*(\d+)", line)
        if not r:
            continue
        cells = [c.strip() for c in r.group(1).split(",")]
        rows.append((int(r.group(2)),
                     [c.strip('"') if c.startswith('"') else None for c in cells]))
    if len(rows) != 57:
        sys.exit("expected 57 rows, found %d" % len(rows))
    return rows


def render():
    seen = set()
    out = []
    for group, cells in parse():
        for slot, name in enumerate(cells):
            if not name or not name.lower().startswith("bgm_"):
                continue
            first = name.lower() not in seen
            seen.add(name.lower())
            out.append((group, slot, name, first))
    lines = [
        "#pragma once",
        "// GENERATED by tools/gen_saturn_bgm_table.py - do not edit by hand.",
        "//",
        "// Which Saturn music-pack song is which PC BGM wav. The PC loads a room's",
        "// music by group; the Saturn's /SND/BGM<group in hex>.CDP is the same group",
        "// and song k of the pack is channel k (g_BgmNameTable[group][k]).",
        "// `first` is false for a name a lower group already provided: the PC has one",
        "// file per name, so the first (lowest) group's render is the one written.",
        "",
        "#include <cstdint>",
        "",
        "namespace re1 {",
        "",
        "struct SaturnBgmEntry {",
        "    uint8_t group;      // /SND/BGM%02X.CDP",
        "    uint8_t song;       // song in the pack's sequence bank = BGM channel",
        "    const char* name;   // Sound/<name>.wav, as g_BgmNameTable spells it",
        "    bool first;",
        "};",
        "",
        "inline constexpr SaturnBgmEntry kSaturnBgm[] = {",
    ]
    for group, slot, name, first in out:
        lines.append('    {0x%02X, %d, "%s", %s},' %
                     (group, slot, name, "true" if first else "false"))
    lines += ["};", "", "}  // namespace re1", ""]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur.replace("\r\n", "\n") != text:
            print("%s is stale" % OUT)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
