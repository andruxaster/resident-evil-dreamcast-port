// SaturnTick.h - the Sega Saturn's Tick.
//
// The Tick is not a Hunter with a new mesh. The Saturn swaps the Hunter's model
// for EM1016 in the stage-byte-2 module (saturn/SaturnModels.h), and that
// module, GAME2.PRG, carries its OWN build of the Hunter's AI: the entity still
// has type 6 and the Hunter's tables, but a handful of its functions are
// different, and the model has an arm that stretches. Everything here is read
// out of GAME2 (loaded at 0x0602B000; every address below is GAME2 unless it
// says otherwise) and compared against the PC Hunter and the Saturn's GAME1 /
// GAME5 copies, which are the PC Hunter's code. Every other Hunter function in
// GAME2 compares identical (the script-driven states included).
//
// What differs, and where it hooks into entities/Hunter.cpp:
//
//   state init      0x0606C824  saturn_tick_state_init      (end of hunter_state_init)
//   variant roll    0x0606D074  saturn_tick_variant_hold    (hunter_variant_dispatch)
//   variant 0       0x0606D10C  saturn_tick_variant_0_leap  (the leap tail)
//   variant 2       0x0606D484  saturn_tick_variant_2_ai    (replaces hunter_variant_2_ai)
//   chase  (bhv 1)  0x0606D998  saturn_tick_behavior_chase  (replaces hunter_behavior_chase)
//   pounce (bhv 5)  0x0606DE98  saturn_tick_behavior_pounce (replaces hunter_behavior_pounce)
//                   0x0606DF24  the stab itself, behind the pounce
//   hold   (bhv 7)  0x0606E78C  saturn_tick_behavior_grabhold (replaces hunter_behavior_grabhold)
//   animator        0x06070604  tick_anim_step              (stands in for Joint_move)
//   slot alloc      0x060705C4  / reset 0x060705A8 (from the room init, 0x0603D36C)
//
// Four of the Tick's poses are not in the EMD at all: the walk (animation
// 0x80), the stab wind-up (0x81), the retract (0x82) and the decapitation (0x83)
// are keyframe tables in the module's data (SaturnTickAnim.cpp, generated by
// tools/gen_tick_tables.py). The EMD's PS1 section, which is the Hunter's, still
// serves everything else: the swipe, the dodge, the death.
//
// The keys are NOT in the PS1 data's rotation order. GAME2 draws a Tick with
// its own routine (0x060708B0) only while a keyframe animation plays
// (animationId bit 0x80), and that routine composes Rz Ry Rx where the generic
// one (0x060381A8, the PS1 data) composes Rx Ry Rz. The PC stores its matrices
// Y-flipped (drawn = D * stored * D, D = diag(1,-1,1)), so a key is stored as
// D * Rz Ry Rx * D - see tick_key_to_pc_angles. Drawn right, the walk is the
// Hunter's forward hunch and the stab arm is level and 13-19 degrees off the
// heading, which the 0xA0 the stab turns the body by cancels.
//
// The stretching arm is parts 4 -> 5 -> 6 (the left arm chain). The Saturn draws
// them with a per-part scale (GAME2 0x060708B0): flags 0x20 scale the part's
// MESH along its Y axis, flag 0x100 scales the part's own OFFSET along Y, and
// the saved world matrix - what children and hit tests read - stays unscaled.
// The module installs all three joints' flags at init and keeps one scale value
// for the three (Entity +0x186). On the PC the same effect is a hook in
// rotate_entity (GteMatrix.cpp).
//
// The Entity has no free bytes for the Tick's three per-instance values (the PC
// struct is exactly 0x18C and the Hunter uses to +0x18A), so they live in a side
// table keyed by the Entity pointer; the Saturn keeps them at +0x186 (arm
// scale), +0x188 (animator slot) and +0x189 (stab sub-state).
//
// Everything here is gated on g_bSaturnMode by the callers, so OG and DC never
// reach it.
#pragma once

struct Entity;
struct MATRIX;

// The Hunter's entity type, and the joints of the stretching arm.
#define SATURN_TICK_ENTITY_ID     6
#define SATURN_TICK_ARM_FIRST     4
#define SATURN_TICK_ARM_LAST      6

// The Saturn's animator slot table has four 0x20-byte slots (0x0609D5F4). The
// port keeps eight so an over-full room cannot index past the table the way
// the Saturn's slot 0xFF would.
#define SATURN_TICK_SLOTS         8
#define SATURN_TICK_JOINTS        16
#define SATURN_TICK_ANIMS         4

// ---- the generated animation tables (SaturnTickAnim.cpp) -------------------

struct SaturnTickKey {
    unsigned short time;   // the frame this key takes over; 0xFFFE ends the array
    short x, y, z;         // root: translation; joint: rotation (4096 = 360 degrees)
};
struct SaturnTickAnim {
    unsigned short frames; // last frame number; the animator wraps past it
    unsigned short root;   // first record of the root key array
    unsigned short joint[SATURN_TICK_JOINTS]; // first record of each joint's array
};
extern const SaturnTickKey  g_saturnTickKeys[];
extern const SaturnTickAnim g_saturnTickAnims[SATURN_TICK_ANIMS];

// ---- Hunter.cpp hooks (ENTITY is the Hunter) -------------------------------

// True when ENTITY is a Tick: Saturn mode, the Tick's stage, entity type 6.
// Callers test g_bSaturnMode first, as everywhere else.
int saturn_tick_active(void);

// The room init (0x0603D36C -> 0x060705A8): every animator slot back to free.
void saturn_tick_room_reset(void);

// End of hunter_state_init. 0x0606C824 allocates the animator slot first and,
// last, installs the arm parts' scale flags; here that is the slot and the
// arm scale.
void saturn_tick_state_init(void);

// Inside hunter_variant_dispatch, after the coward branch. When the PLAYER's
// being-attacked flag (+0x8A) is 0x55 the Tick takes state block 0x01010100
// (state 1, ignore 1, behaviour 1) and skips the variant roll. Returns 1 when
// it did. Nothing in the campaign writes 0x55, so on the PC this is inert; it
// is ported because it is in the module.
int saturn_tick_variant_hold(void);

// The tail of variant 0: close enough and aimed, with the pounce latch up. The
// Hunter rolls an aimed leap (hunter_roll_leap); the Tick just steps and starts
// the stab. Replaces the hunter_roll_leap() call there, and its turn tolerance
// (0x20, the Hunter's is 0x100) is the caller's.
void saturn_tick_variant_0_leap(void);

// Variants 2 and 7 (hunter_variant_2_ai).
void saturn_tick_variant_2_ai(void);

// Behaviours 1, 5 and 7 (hunter_behavior_chase / _pounce / _grabhold).
void saturn_tick_behavior_chase(void);
void saturn_tick_behavior_pounce(void);
void saturn_tick_behavior_grabhold(void);

// ---- the player's side of the bite (PlayerAnimations.cpp) -------------------
//
// The Hunter's bite sets the player to animationId 7 / animFrameId 6, which the
// player dispatcher (window 2, 0x26 + animFrameId) sends to g_playerAnimFunctions
// [44]. On the PC that is player_anim_dispatch_4c2ac8, which kills the player in
// its first state. GAME2 installs its own function there (0x0606FF78, from the
// table setup 0x06052FB8): eight states, hurt first, decapitation only when the
// Tick's hold sets action_state = 4 on frame 10 of its animation 0x83. It
// applies to everything that bites in the Tick's stage, as on the Saturn.
// Returns 1 when it handled the call (Saturn mode, the Tick's stage).
int saturn_tick_player_bitten(void);

// ---- rotate_entity hook (GteMatrix.cpp) ------------------------------------
//
// rotate_entity builds world = parent * local for each joint and recurses with
// that world. For the Tick's arm joints it asks these four, in this order:
//
//   saturn_tick_joint_scaled   - is `joint` one of the arm's three on a Tick?
//   saturn_tick_scale_local    - the local transform with the part's own offset
//                                scaled (joints 5 and 6, flag 0x100)
//   saturn_tick_scale_mesh     - after composing: remember the unscaled world
//                                for the children, scale the one the mesh is
//                                drawn with (joints 4 and 5, flag 0x20)
//   saturn_tick_child_parent   - the matrix the children compose from
int          saturn_tick_joint_scaled(const Entity* ent, unsigned char joint);
void         saturn_tick_scale_local(const Entity* ent, unsigned char joint, MATRIX* local);
void         saturn_tick_scale_mesh(const Entity* ent, unsigned char joint, MATRIX* world);
const MATRIX* saturn_tick_child_parent(const Entity* ent, unsigned char joint,
                                       const MATRIX* world);
